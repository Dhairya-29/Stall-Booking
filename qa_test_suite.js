const fs = require('fs');
const path = require('path');

const BASE = 'http://localhost:3000';
const ADMIN_PASS = 'admin123';

// 1x1 transparent PNG base64
const VALID_PNG_BASE64 = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk+M9QDwADhgGAWjR9awAAAABJRU5ErkJggg==';
const INVALID_IMG_BASE64 = 'data:image/png;base64,SGVsbG8gV29ybGQ='; // Not a valid image header

const results = [];

function record(suite, testName, passed, details = '') {
  results.push({ suite, testName, passed, details });
  console.log(`${passed ? '✓ PASS' : '✗ FAIL'} [${suite}] ${testName}${details ? ' - ' + details : ''}`);
}

async function request(url, options = {}) {
  const res = await fetch(BASE + url, options);
  let data;
  try {
    data = await res.json();
  } catch (e) {
    data = await res.text();
  }
  return { status: res.status, ok: res.ok, data };
}

async function runQA() {
  console.log('=== STARTING QA INTEGRATION TEST SUITE ===\n');

  // ----------------------------------------------------
  // MODULE 1: Server & Static Assets
  // ----------------------------------------------------
  const homeRes = await fetch(BASE + '/');
  record('Static Assets', 'Home page index.html serves HTTP 200', homeRes.status === 200);

  const adminPageRes = await fetch(BASE + '/admin.html');
  record('Static Assets', 'Admin page admin.html serves HTTP 200', adminPageRes.status === 200);

  const layoutRes = await request('/api/layout');
  record('API Layout', 'Hall layout returns 27 stalls', layoutRes.ok && Array.isArray(layoutRes.data) && layoutRes.data.length === 27, `Count: ${layoutRes.data?.length}`);

  // ----------------------------------------------------
  // MODULE 2: User Authentication & Validation
  // ----------------------------------------------------
  // Test invalid name
  const badName = await request('/api/auth/send-otp', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ name: 'A', phone: '9988776655' })
  });
  record('Auth Validation', 'Rejects name < 2 characters', badName.status === 400 && badName.data.error.includes('name'));

  // Test invalid phone
  const badPhone = await request('/api/auth/send-otp', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ name: 'Valid Name', phone: '12345' })
  });
  record('Auth Validation', 'Rejects non-10-digit mobile number', badPhone.status === 400 && badPhone.data.error.includes('10-digit'));

  // Test invalid email
  const badEmail = await request('/api/auth/send-otp', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ name: 'Valid Name', phone: '9876543211', email: 'not-an-email' })
  });
  record('Auth Validation', 'Rejects invalid email format', badEmail.status === 400 && badEmail.data.error.includes('email'));

  // Valid OTP request
  const testPhone = '98' + Math.floor(10000000 + Math.random() * 90000000);
  const validOtpReq = await request('/api/auth/send-otp', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ name: 'QA Tester', phone: testPhone, email: 'tester@example.com' })
  });
  record('Auth Flow', 'Sends OTP for valid details', validOtpReq.ok && validOtpReq.data.ok === true);

  // Rate limiting OTP request (< 30s)
  const rapidOtpReq = await request('/api/auth/send-otp', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ name: 'QA Tester', phone: testPhone, email: 'tester@example.com' })
  });
  record('Auth Security', 'Throttles rapid consecutive OTP requests (30s cooldown)', rapidOtpReq.status === 429);

  // We need the OTP code generated by the server. In test mode it was printed to stdout.
  // Let's inspect the server log or verify with incorrect OTP first.
  const badVerify = await request('/api/auth/verify', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ phone: testPhone, otp: '000000' })
  });
  record('Auth Security', 'Rejects incorrect OTP', badVerify.status === 400 && badVerify.data.error === 'Incorrect OTP');

  // Find the active server task log
  const tasksDir = 'C:\\Users\\dhair\\.gemini\\antigravity-ide\\brain\\84fedec0-eafa-4fd7-b8ed-57c219e2c197\\.system_generated\\tasks';
  const logFiles = fs.readdirSync(tasksDir).filter(f => f.endsWith('.log')).map(f => path.join(tasksDir, f));
  // Find log file containing 'Running on http://localhost:3000'
  let srvLog = '';
  for (const f of logFiles.sort((a,b) => fs.statSync(b).mtimeMs - fs.statSync(a).mtimeMs)) {
    const content = fs.readFileSync(f, 'utf8');
    if (content.includes('Running on http://localhost:3000')) {
      srvLog = content;
      break;
    }
  }
  const otpMatches = [...srvLog.matchAll(new RegExp(`OTP for ${testPhone}: (\\d{6})`, 'g'))];
  const testOtp = otpMatches.length ? otpMatches[otpMatches.length - 1][1] : null;

  let userToken = '';
  if (testOtp) {
    const goodVerify = await request('/api/auth/verify', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ phone: testPhone, otp: testOtp })
    });
    userToken = goodVerify.data?.token;
    record('Auth Flow', 'Verifies correct OTP and returns auth session token', goodVerify.ok && !!userToken);
  } else {
    record('Auth Flow', 'Verifies correct OTP and returns auth session token', false, 'Could not retrieve OTP from server log');
  }

  // Check /api/me
  const meRes = await request('/api/me', {
    headers: { Authorization: `Bearer ${userToken}` }
  });
  record('User Profile', '/api/me returns authenticated user details', meRes.ok && meRes.data.phone === testPhone);

  // Check protected route without token (401)
  const noAuthRes = await request('/api/me');
  record('API Security', 'Unauthenticated requests to /api/me rejected with 401', noAuthRes.status === 401);

  // ----------------------------------------------------
  // MODULE 3: Events & Stalls
  // ----------------------------------------------------
  const eventsRes = await request('/api/events', {
    headers: { Authorization: `Bearer ${userToken}` }
  });
  record('Events Module', 'Fetches active events list', eventsRes.ok && Array.isArray(eventsRes.data) && eventsRes.data.length > 0);
  const activeEvent = eventsRes.data[0];

  const stallsRes = await request(`/api/events/${activeEvent.id}/stalls`, {
    headers: { Authorization: `Bearer ${userToken}` }
  });
  record('Stalls Module', 'Fetches stalls availability and pricing for event', stallsRes.ok && stallsRes.data.status !== undefined && stallsRes.data.price > 0);

  // ----------------------------------------------------
  // MODULE 4: Booking & Hold Flow
  // ----------------------------------------------------
  // Test hold with > 10 stalls (boundary test)
  const tooManyStalls = await request('/api/bookings', {
    method: 'POST',
    headers: { Authorization: `Bearer ${userToken}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ eventId: activeEvent.id, stalls: ['L1','L2','L3','L4','L5','L6','L7','T8','A2','A3','A4'] })
  });
  record('Booking Validation', 'Rejects bookings with more than 10 stalls', tooManyStalls.status === 400);

  // Test hold with invalid stall ID
  const invalidStall = await request('/api/bookings', {
    method: 'POST',
    headers: { Authorization: `Bearer ${userToken}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ eventId: activeEvent.id, stalls: ['XYZ99'] })
  });
  record('Booking Validation', 'Rejects unknown stall IDs', invalidStall.status === 400);

  // Pick available stalls dynamically
  const available = layoutRes.data.map(s => s.id).filter(id => !stallsRes.data.status[id]);
  const s1 = available[0] || 'B8';
  const s2 = available[1] || 'B9';
  const s3 = available[2] || 'B10';

  // Valid hold for stalls s1 and s2
  const validHold = await request('/api/bookings', {
    method: 'POST',
    headers: { Authorization: `Bearer ${userToken}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ eventId: activeEvent.id, stalls: [s1, s2] })
  });
  const booking1 = validHold.data;
  record('Booking Flow', 'Successfully reserves stalls with 10-minute hold', validHold.ok && booking1.status === 'held');

  // Test Double Booking Conflict: Attempting to hold s1 while currently held
  const conflictHold = await request('/api/bookings', {
    method: 'POST',
    headers: { Authorization: `Bearer ${userToken}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ eventId: activeEvent.id, stalls: [s1, s3] })
  });
  record('Concurrency / Race Conditions', 'Blocks double-booking on currently held stalls (409 Conflict)', conflictHold.status === 409 && conflictHold.data.error.includes(s1));

  // ----------------------------------------------------
  // MODULE 5: Payment Submission & Verification
  // ----------------------------------------------------
  // Test invalid UTR (< 8 chars)
  const shortUtr = await request(`/api/bookings/${booking1.id}/pay`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${userToken}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ utr: 'SHORT', screenshot: VALID_PNG_BASE64 })
  });
  record('Payment Validation', 'Rejects UTR shorter than 8 alphanumeric characters', shortUtr.status === 400);

  // Test invalid screenshot format (corrupted header)
  const badImage = await request(`/api/bookings/${booking1.id}/pay`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${userToken}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ utr: 'UTR123456789', screenshot: INVALID_IMG_BASE64 })
  });
  record('Payment Validation', 'Validates image magic bytes (rejects fake image base64)', badImage.status === 400 && badImage.data.error.includes('valid image'));

  // Valid payment submission
  const testUtr = 'UTR' + Date.now();
  const validPay = await request(`/api/bookings/${booking1.id}/pay`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${userToken}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ utr: testUtr, screenshot: VALID_PNG_BASE64 })
  });
  record('Payment Flow', 'Submits payment details, status transitions to "submitted"', validPay.ok && validPay.data.status === 'submitted');

  // Test duplicate UTR prevention
  // Create another booking
  const secondHold = await request('/api/bookings', {
    method: 'POST',
    headers: { Authorization: `Bearer ${userToken}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ eventId: activeEvent.id, stalls: [s3] })
  });
  const booking2 = secondHold.data;
  const dupUtrPay = await request(`/api/bookings/${booking2.id}/pay`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${userToken}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ utr: testUtr, screenshot: VALID_PNG_BASE64 }) // same UTR
  });
  record('Payment Security', 'Rejects duplicate UTR already used in another booking (409 Conflict)', dupUtrPay.status === 409);

  // ----------------------------------------------------
  // MODULE 6: Admin Operations
  // ----------------------------------------------------
  // Admin auth check
  const badAdminReq = await request('/api/admin/bookings', { headers: { 'x-admin': 'wrong_password' } });
  record('Admin Security', 'Unauthorized admin access blocked (401)', badAdminReq.status === 401);

  const goodAdminReq = await request('/api/admin/bookings', { headers: { 'x-admin': ADMIN_PASS } });
  record('Admin Dashboard', 'Admin fetches all bookings & event metrics', goodAdminReq.ok && goodAdminReq.data.bookings.length > 0);

  // Admin view screenshot
  const shotRes = await fetch(`${BASE}/api/admin/bookings/${booking1.id}/screenshot`, { headers: { 'x-admin': ADMIN_PASS } });
  record('Admin Dashboard', 'Admin retrieves uploaded payment screenshot image', shotRes.status === 200 && shotRes.headers.get('content-type').includes('image'));

  // Admin Approve Booking
  const approveRes = await request(`/api/admin/bookings/${booking1.id}/approve`, {
    method: 'POST',
    headers: { 'x-admin': ADMIN_PASS }
  });
  record('Admin Approval', 'Admin approves booking, generates receipt number (e.g. RC-0001)', approveRes.ok && approveRes.data.status === 'approved' && !!approveRes.data.receiptNo);

  // Check Public Receipt Page
  const receiptRes = await fetch(`${BASE}/receipt/${booking1.id}`);
  const receiptHtml = await receiptRes.text();
  record('Customer Receipt', 'Receipt page renders with CONFIRMED status and print button', receiptRes.status === 200 && receiptHtml.includes('CONFIRMED') && receiptHtml.includes(booking1.stalls.join(', ')));

  // Admin Reject Booking for booking2
  // First pay booking2 with a unique UTR
  const rejectUtr = 'UTR' + (Date.now() + 999);
  await request(`/api/bookings/${booking2.id}/pay`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${userToken}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ utr: rejectUtr, screenshot: VALID_PNG_BASE64 })
  });
  const rejectRes = await request(`/api/admin/bookings/${booking2.id}/reject`, {
    method: 'POST',
    headers: { 'x-admin': ADMIN_PASS }
  });
  record('Admin Rejection', 'Admin rejects booking, stalls released', rejectRes.ok && rejectRes.data.status === 'rejected');

  // Verify booking2 stalls are released
  const updatedStalls = await request(`/api/events/${activeEvent.id}/stalls`, {
    headers: { Authorization: `Bearer ${userToken}` }
  });
  record('Stall Release', 'Rejected booking stalls immediately become available again', updatedStalls.data.status[s3] === undefined);

  // ----------------------------------------------------
  // MODULE 7: Admin Event Management (CRUD)
  // ----------------------------------------------------
  // Create Event with validation failure (price = 0)
  const badEvent = await request('/api/admin/events', {
    method: 'POST',
    headers: { 'x-admin': ADMIN_PASS, 'Content-Type': 'application/json' },
    body: JSON.stringify({ name: 'Free Event', date: '2026-12-01', price: 0 })
  });
  record('Event Management', 'Rejects event creation with price <= 0', badEvent.status === 400);

  // Create valid event
  const newEventRes = await request('/api/admin/events', {
    method: 'POST',
    headers: { 'x-admin': ADMIN_PASS, 'Content-Type': 'application/json' },
    body: JSON.stringify({
      name: 'Diwali Grand Bazaar 2026',
      date: '2026-11-10',
      endDate: '2026-11-12',
      price: 6500,
      time: '10:00 AM - 10:00 PM',
      about: 'Grand shopping festival with over 100 brands at Hotel Shiv.'
    })
  });
  const createdEvent = newEventRes.data?.find(e => e.name === 'Diwali Grand Bazaar 2026');
  record('Event Management', 'Successfully creates new event with dates and description', newEventRes.ok && !!createdEvent);

  // Update Event with custom stall pricing
  if (createdEvent) {
    const updateEventRes = await request(`/api/admin/events/${createdEvent.id}`, {
      method: 'PUT',
      headers: { 'x-admin': ADMIN_PASS, 'Content-Type': 'application/json' },
      body: JSON.stringify({
        name: 'Diwali Grand Bazaar 2026 (Updated)',
        date: '2026-11-10',
        endDate: '2026-11-12',
        price: 6500,
        prices: { 'T8': 9000, 'C1': 8500 }
      })
    });
    const updatedEv = updateEventRes.data?.find(e => e.id === createdEvent.id);
    record('Event Management', 'Updates event details and custom per-stall pricing overrides', updateEventRes.ok && updatedEv?.prices?.['T8'] === 9000);

    // Delete event without active bookings
    const delEventRes = await request(`/api/admin/events/${createdEvent.id}`, {
      method: 'DELETE',
      headers: { 'x-admin': ADMIN_PASS }
    });
    record('Event Management', 'Successfully deletes event with no active bookings', delEventRes.ok && !delEventRes.data?.some(e => e.id === createdEvent.id));
  }

  // Prevent deleting event with active bookings
  const delActiveEvent = await request(`/api/admin/events/${activeEvent.id}`, {
    method: 'DELETE',
    headers: { 'x-admin': ADMIN_PASS }
  });
  record('Event Management', 'Blocks deletion of event that has active bookings (400)', delActiveEvent.status === 400);

  // ----------------------------------------------------
  // SUMMARY
  // ----------------------------------------------------
  const passed = results.filter(r => r.passed).length;
  const failed = results.filter(r => !r.passed).length;
  console.log(`\n========================================`);
  console.log(`QA TEST SUITE SUMMARY: ${passed} PASSED, ${failed} FAILED (${results.length} total)`);
  console.log(`========================================\n`);

  fs.writeFileSync('qa_results.json', JSON.stringify(results, null, 2));
}

runQA().catch(console.error);
